#!/usr/bin/env bash
# Regenerates src/frontend/ruby/generated.rs from the bindings ruby-prism's
# build script writes. Run after bumping ruby-prism: the match is exhaustive,
# so a new prism node type fails the build until this is rerun.
set -euo pipefail

cd "$(dirname "$0")/.."
cargo build --quiet
bindings=$(find target/debug/build -path '*ruby-prism*' -not -path '*ruby-prism-sys*' -name bindings.rs | head -1)
[ -n "$bindings" ] || { echo "gen-ruby-kinds: no ruby-prism bindings.rs under target/" >&2; exit 1; }

snake() { sed -E 's/([a-z0-9])([A-Z])/\1_\2/g' | tr '[:upper:]' '[:lower:]'; }

variants=$(awk '/^pub enum Node/{f=1;next} f&&/^}/{exit} f' "$bindings" | grep -oE '^    [A-Za-z]+ \{' | tr -d ' {')
named=$(awk '/^impl<.pr> [A-Za-z]+<.pr> \{/{cur=$2} /pub fn name\(&self\) -> ConstantId/{sub(/<.*/, "", cur); print cur}' "$bindings")

out=src/frontend/ruby/generated.rs
{
  echo "//! GENERATED by script/gen-ruby-kinds.sh -- do not edit by hand."
  echo
  echo "use ruby_prism::Node;"
  echo
  echo "/// A prism node's kind, and its identifier where prism records one."
  echo "#[allow(clippy::too_many_lines)]"
  echo "pub(super) fn kind_and_name<'pr>(node: &Node<'pr>) -> (&'static str, Option<&'pr [u8]>) {"
  echo "    match node {"
  for v in $variants; do
    kind=$(echo "${v%Node}" | snake)
    if grep -qx "$v" <<<"$named"; then
      method=$(echo "$v" | snake)
      echo "        Node::$v { .. } => (\"$kind\", node.as_$method().map(|n| n.name().as_slice())),"
    else
      echo "        Node::$v { .. } => (\"$kind\", None),"
    fi
  done
  echo "    }"
  echo "}"
} >"$out"
rustfmt --edition 2024 "$out"
echo "wrote $out" >&2
